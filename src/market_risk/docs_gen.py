"""Generate docs/lineage.md, docs/data_quality.md and docs/data_dictionary.md.

Everything is derived from the pipeline SQL, the risk job's table specs and checks.yml,
so documentation cannot drift from the code (CI fails if the committed docs are stale).
Run ``python scripts/build_docs.py`` after changing a model or a check.
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from market_risk.jobs.compute_risk import OUTPUT_TABLES
from market_risk.pipeline_sql import load_models, topological_order
from market_risk.quality.checks import load_checks

DOCS_DIR = Path(__file__).resolve().parents[2] / "docs"
HEADER = "<!-- Generated by scripts/build_docs.py. Do not edit by hand. -->\n\n"

SOURCES = {
    "bronze_ecb_fx_rates": "src_ecb",
    "bronze_index_prices": "src_fred",
    "bronze_risk_factors": "src_ref",
    "bronze_positions": "src_ref",
}
SOURCE_LABELS = {
    "src_ecb": "ECB Data Portal API<br/>EXR daily reference rates",
    "src_fred": "FRED fredgraph.csv<br/>equity index closes",
    "src_ref": "Repository reference CSVs<br/>risk factors, positions",
}
BI_TABLES = [
    "gold_dim_date",
    "gold_dim_risk_factor",
    "gold_dim_position",
    "gold_dim_risk_method",
    "gold_fact_position_exposure_daily",
    "gold_fact_var_daily",
    "gold_fact_risk_contribution",
    "gold_fact_var_backtest",
    "gold_backtest_summary",
]


def _catalog():
    models = load_models()
    tables = {}
    for name in topological_order(models):
        m = models[name]
        tables[name] = {
            "layer": m.layer,
            "kind": m.kind.replace("_", " "),
            "producer": f"pipeline: `{m.source_file.relative_to(DOCS_DIR.parent).as_posix()}`",
            "description": m.comment or "",
            "upstream": list(m.upstream),
            "columns": [(c.name, c.data_type, c.comment or "") for c in m.columns],
            "expectations": m.expectations,
        }
    for name, spec in OUTPUT_TABLES.items():
        tables[name] = {
            "layer": "gold",
            "kind": "delta table",
            "producer": "risk job: `src/market_risk/jobs/compute_risk.py`",
            "description": spec.description,
            "upstream": list(spec.upstream),
            "columns": [(c, t, comment) for c, (t, comment) in spec.columns.items()],
            "expectations": [],
        }
    downstream = defaultdict(list)
    for name, t in tables.items():
        for up in t["upstream"]:
            downstream[up].append(name)
    return tables, downstream


def lineage_md() -> str:
    tables, downstream = _catalog()
    lines = [
        HEADER + "# Lineage\n",
        "Every table in the lakehouse, where it comes from and what reads it. Unity Catalog also",
        "captures column-level lineage at runtime for the pipeline models; the risk job records its",
        "inputs in the `lineage.upstream` table property of each table it writes.\n",
        "```mermaid",
        "flowchart LR",
    ]
    for sid, label in SOURCE_LABELS.items():
        lines.append(f'  {sid}[("{label}")]')
    groups = {
        "bronze": "Bronze",
        "silver": "Silver",
        "gold": "Gold (pipeline)",
        "risk": "Gold (risk job)",
    }
    for key, title in groups.items():
        lines.append(f'  subgraph {key}["{title}"]')
        for name, t in tables.items():
            in_group = (
                (t["layer"] == key and "pipeline" in t["producer"]) if key != "risk" else "risk job" in t["producer"]
            )
            if in_group:
                lines.append(f"    {name}")
        lines.append("  end")
    lines.append('  powerbi[["Power BI dashboard"]]')
    for name, src in SOURCES.items():
        lines.append(f"  {src} --> {name}")
    for name, t in tables.items():
        for up in t["upstream"]:
            lines.append(f"  {up} --> {name}")
    for name in BI_TABLES:
        lines.append(f"  {name} -.-> powerbi")
    lines.append("```\n")

    lines.append("## Tables\n")
    lines.append("| Table | Layer | Produced by | Reads from | Read by |")
    lines.append("|---|---|---|---|---|")
    for name, t in tables.items():
        ups = ", ".join(f"`{u}`" for u in t["upstream"]) or SOURCE_LABELS.get(SOURCES.get(name, ""), "").replace(
            "<br/>", ", "
        )
        downs = ", ".join(f"`{d}`" for d in sorted(downstream[name]))
        if name in BI_TABLES:
            downs = (downs + ", " if downs else "") + "Power BI"
        lines.append(f"| `{name}` | {t['layer']} | {t['producer']} | {ups} | {downs} |")
    return "\n".join(lines) + "\n"


def quality_summary() -> dict:
    tables, _ = _catalog()
    checks = load_checks()
    n_exp = sum(len(t["expectations"]) for t in tables.values())
    covered = {n for n, t in tables.items() if t["expectations"]} | {c.table for c in checks}
    return {
        "tables": len(tables),
        "tables_covered": len(covered & set(tables)),
        "expectations": n_exp,
        "checks": len(checks),
        "total": n_exp + len(checks),
    }


def data_quality_md() -> str:
    tables, _ = _catalog()
    checks = load_checks()
    by_table = defaultdict(list)
    for c in checks:
        by_table[c.table].append(c)
    s = quality_summary()
    lines = [
        HEADER + "# Data quality\n",
        f"**{s['total']} data quality tests covering {s['tables_covered']} of {s['tables']} tables**: "
        f"{s['expectations']} pipeline expectations (row-level, enforced while data flows through the "
        f"Lakeflow pipeline) and {s['checks']} post-load checks (keys, referential integrity, freshness, "
        "reconciliations and the risk job outputs, run by job task `data_quality_checks`).\n",
        "Expectation actions: **warn** keeps the row and records the violation in the pipeline event log, "
        "**drop row** removes it, **fail update** stops the pipeline. Post-load checks with severity "
        "**error** fail the job; **warn** checks are only recorded in `ops_dq_results`.\n",
        "| Table | Expectations | Post-load checks | Total |",
        "|---|---:|---:|---:|",
    ]
    for name, t in tables.items():
        e, c = len(t["expectations"]), len(by_table[name])
        lines.append(f"| `{name}` | {e} | {c} | {e + c} |")
    lines.append(f"| **Total** | **{s['expectations']}** | **{s['checks']}** | **{s['total']}** |\n")

    for name, t in tables.items():
        lines.append(f"## `{name}`\n")
        if t["expectations"]:
            lines.append("| Expectation | Rule | On violation |")
            lines.append("|---|---|---|")
            for exp in t["expectations"]:
                rule = exp.expression.replace("|", "\\|")
                lines.append(f"| `{exp.name}` | `{rule}` | {exp.action_label} |")
            lines.append("")
        if by_table[name]:
            lines.append("| Check | Type | Severity | What it verifies |")
            lines.append("|---|---|---|---|")
            for c in by_table[name]:
                lines.append(f"| `{c.name}` | {c.check_type} | {c.severity} | {c.description} |")
            lines.append("")
    return "\n".join(lines)


def data_dictionary_md() -> str:
    tables, _ = _catalog()
    lines = [HEADER + "# Data dictionary\n"]
    for name, t in tables.items():
        lines.append(f"## `{name}`\n")
        lines.append(f"*{t['layer']} {t['kind']}, {t['producer']}*\n")
        lines.append(t["description"] + "\n")
        lines.append("| Column | Type | Description |")
        lines.append("|---|---|---|")
        for col, typ, comment in t["columns"]:
            lines.append(f"| `{col}` | {typ} | {comment} |")
        lines.append("")
    return "\n".join(lines)


GENERATED = {
    "lineage.md": lineage_md,
    "data_quality.md": data_quality_md,
    "data_dictionary.md": data_dictionary_md,
}


def build(docs_dir: Path = DOCS_DIR) -> list[Path]:
    docs_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, fn in GENERATED.items():
        path = docs_dir / name
        path.write_text(fn())
        written.append(path)
    return written
